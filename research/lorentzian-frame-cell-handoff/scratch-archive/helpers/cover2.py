"""Exact branch cover number of a reader set R inside s^perp (labels real vectors, form F):
cover(s) = min #hyperplanes {y : <e_i, y> = 0} (e_i in the label space, not parallel to s) whose union contains R.
cover 1: R spans <= h-2 inside s^perp.  cover 2: exists quadratic form (e1.y)(e2.y) vanishing on R:
search: for each hyperplane H spanned by readers (rank h-2 subsets inside span R), test whether R \ H lies in a
hyperplane.  Exhaustive over hyperplanes generated by readers (a covering hyperplane can be taken spanned by the
readers it contains when those span a hyperplane; else it contains < h-2 independent readers and we also try them)."""
import numpy as np, itertools
def span_rank(V): return np.linalg.matrix_rank(np.array(V, dtype=float), tol=1e-8) if len(V) else 0
def cover_number(R, ambient_dim, maxc=3):
    R = [np.array(r, dtype=float) for r in R]
    d = span_rank(R)
    if d <= ambient_dim - 1 - 1 + 0 and d < ambient_dim - 1:   # readers inside a proper subspace of s^perp
        pass
    # cover 1 iff readers lie in a hyperplane of s^perp, i.e. span(R) has dim <= (h-1)-1
    if d <= ambient_dim - 2: return 1
    # cover 2 test: find hyperplane H (dim d-1 inside span R) containing a maximal set of readers, rest in another hyperplane
    n = len(R)
    Rm = np.array(R)
    # candidate hyperplanes: spanned by d-1 independent readers; dedupe by normal (within span R)
    B = np.linalg.svd(Rm)[2][:d]          # orthonormal basis of span R (euclidean, fine for incidence)
    Y = Rm @ B.T                          # coords in span R (n x d)
    seen = set()
    idx = list(range(n))
    rng = np.random.default_rng(0)
    # enumerate normals via random (d-1)-subsets + all of them if small
    tried = 0
    combos = itertools.combinations(idx, d - 1) if n <= 40 else (tuple(rng.choice(n, d - 1, replace=False)) for _ in range(20000))
    for comb in combos:
        A = Y[list(comb)]
        if np.linalg.matrix_rank(A, tol=1e-8) < d - 1: continue
        nrm = np.linalg.svd(A)[2][-1]
        key = tuple(np.round(nrm / nrm[np.argmax(np.abs(nrm))], 6))
        if key in seen: continue
        seen.add(key); tried += 1
        on = np.abs(Y @ nrm) < 1e-8
        rest = Y[~on]
        if len(rest) == 0 or np.linalg.matrix_rank(rest, tol=1e-8) <= d - 1:
            return 2
    return 3   # (>= 3 or not found)
